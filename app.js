const $ = id => document.getElementById(id);
const t = k => (I18N[LANG] && I18N[LANG][k]) || I18N.my[k] || k;

function toast(msg){
  const el = $("toast"); el.textContent = msg; el.classList.add("show");
  setTimeout(()=>el.classList.remove("show"), 1600);
}
function copyText(s){
  (navigator.clipboard ? navigator.clipboard.writeText(s) : Promise.reject())
    .then(()=>toast(t("copied")))
    .catch(()=>{ const ta=document.createElement("textarea"); ta.value=s; document.body.appendChild(ta); ta.select(); document.execCommand("copy"); ta.remove(); toast(t("copied")); });
}

function ballsHTML(digits, sm){
  return digits.map(d=>`<div class="ball${sm?" sm":""}">${d}</div>`).join("");
}
function posHTML(labels, sm){
  return labels.map(l=>`<span${sm?' style="width:44px"':""}>${l}</span>`).join("");
}

function renderLatest(){
  if(D3 && D3.latest){
    const L = D3.latest;
    $("i3d").textContent = L.issue; $("d3d").textContent = L.date;
    $("b3d").innerHTML = ballsHTML(L.digits);
    $("p3d").innerHTML = posHTML(t("pos3d"));
    $("s3d").textContent = (L.extra && L.extra.shijihao) ? L.extra.shijihao.join(" ") : "—";
  }
  if(D5 && D5.latest){
    const L = D5.latest;
    $("ipl5").textContent = L.issue; $("dpl5").textContent = L.date;
    $("bpl5").innerHTML = ballsHTML(L.digits);
    $("ppl5").innerHTML = posHTML(t("pos5d"));
    $("ipl3").textContent = L.issue;
    $("bpl3").innerHTML = ballsHTML(L.digits.slice(0,3), true);
  }
  const upd = [D3&&D3.updated, D5&&D5.updated].filter(Boolean).sort().pop();
  if(upd) $("upd").textContent = new Date(upd).toLocaleString(LANG==="zh"?"zh-CN":LANG==="en"?"en-US":"my-MM");
}

function renderFreq(){
  const mk = (data, posLabels, el) => {
    if(!data || !data.history.length) return;
    const H = data.history.slice(-100);
    let html = "";
    posLabels.forEach((pl, pi) => {
      const cnt = Array(10).fill(0);
      H.forEach(h => cnt[h.digits[pi]]++);
      const mx = Math.max(...cnt);
      html += `<div class="freq-pos"><h3>${pl}</h3>` + cnt.map((c,d)=>
        `<div class="freq-row"><span class="dg">${d}</span><div class="bar"><div class="fill" style="width:${mx?Math.round(c/mx*100):0}%"></div></div><span class="ct">${c}</span></div>`
      ).join("") + `</div>`;
    });
    $(el).innerHTML = html;
  };
  mk(D3, t("pos3d"), "f3d");
  mk(D5, t("pos5d"), "fpl5");
}

function renderHist(){
  const mk = (data, el, extraCol) => {
    if(!data) return;
    $(el).innerHTML = data.history.slice().reverse().map(h=>{
      const ec = extraCol && h.extra && h.extra.shijihao ? `<td>${h.extra.shijihao.join(" ")}</td>` : (extraCol ? "<td>—</td>" : "");
      return `<tr><td>${h.issue}</td><td>${h.date}</td><td class="res">${h.digits.join(" ")}</td>${ec}</tr>`;
    }).join("");
  };
  mk(D3, "h3d", true);
  mk(D5, "hpl5", false);
}

function renderFaq(){
  $("faq").innerHTML = t("faq").map(([q,a])=>`<details><summary>${q}</summary><p>${a}</p></details>`).join("");
}

